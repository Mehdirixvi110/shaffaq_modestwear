// Idempotent, provider-agnostic seeding of the editorial content. The policy refresh
// only touches rows still holding the original placeholder, so it never clobbers the
// owner's edits; blog posts insert-or-ignore by slug. Safe to run against any database.
export async function seedEditorialContent(connection: DatabaseConnection) {
  const insertPolicy = connection.prepare("INSERT OR IGNORE INTO policies (slug, title, content, is_template) VALUES (?, ?, ?, ?)");
  const refreshTemplatePolicy = connection.prepare("UPDATE policies SET title = ?, content = ?, is_template = ? WHERE slug = ? AND content LIKE 'Template requiring%'");
  for (const [slug, title, content, isTemplate] of policyRows) {
    await insertPolicy.run(slug, title, content, isTemplate);
    await refreshTemplatePolicy.run(title, content, isTemplate, slug);
  }
  const insertPost = connection.prepare(`INSERT OR IGNORE INTO blog_posts (slug, title, excerpt, body, cover_image_path, cover_image_alt, author, status, published_at, seo_title, seo_description)
    VALUES (?, ?, ?, ?, ?, ?, 'SHAFFAQ', 'PUBLISHED', ?, ?, ?)`);
  const blogBaseTime = Date.now();
  for (const [index, [slug, title, excerpt, body, cover]] of blogRows.entries()) {
    await insertPost.run(slug, title, excerpt, body, cover, title, blogBaseTime - index * 86_400_000, title, excerpt);
  }
}
